// nixos-shield reference tool: turn a service security contract into an nftables ruleset.
//
// This is a small, dependency-free demonstration of the core idea behind nixos-shield:
// a service declares what it needs, and everything else is denied. Federation flows are
// named (not fixed IPs), so a hardened server keeps talking to the fediverse.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
)

type Contract struct {
	Service string  `json:"service"`
	Network Network `json:"network"`
}

type Network struct {
	Inbound    []int    `json:"inbound"`
	Federation []string `json:"federation"`
	Outbound   []string `json:"outbound"`
}

type rule struct {
	proto string
	port  int
	note  string
}

var serviceName = regexp.MustCompile(`^[a-zA-Z0-9][a-zA-Z0-9._-]{0,63}$`)

// Named flows map to concrete ports. Federation destinations are dynamic, so we allow
// the outbound protocol rather than a fixed address list.
var flows = map[string][]rule{
	"dns":         {{"udp", 53, "dns"}, {"tcp", 53, "dns"}},
	"http":        {{"tcp", 80, "http"}},
	"https":       {{"tcp", 443, "https"}},
	"activitypub": {{"tcp", 443, "activitypub federation"}},
	"matrix":      {{"tcp", 8448, "matrix federation"}},
	"smtp":        {{"tcp", 25, "smtp federation"}, {"tcp", 587, "smtp submission"}},
}

func main() {
	if len(os.Args) == 2 && (os.Args[1] == "-h" || os.Args[1] == "--help") {
		showEnterprise()
		fmt.Println("usage: nixos-shield <contract.json>")
		return
	}
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: nixos-shield <contract.json>")
		os.Exit(2)
	}
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, "read contract:", err)
		os.Exit(1)
	}
	var c Contract
	if err := json.Unmarshal(data, &c); err != nil {
		fmt.Fprintln(os.Stderr, "parse contract:", err)
		os.Exit(1)
	}
	if err := validate(c); err != nil {
		fmt.Fprintln(os.Stderr, "validate contract:", err)
		os.Exit(1)
	}
	showEnterprise()
	fmt.Print(generate(c))
}

func validate(c Contract) error {
	if !serviceName.MatchString(c.Service) {
		return fmt.Errorf("service needs a 1–64 character identifier (letters, digits, dots, underscores or hyphens)")
	}
	for _, port := range c.Network.Inbound {
		if port < 1 || port > 65535 {
			return fmt.Errorf("inbound port %d is outside 1–65535", port)
		}
	}
	for _, names := range [][]string{c.Network.Outbound, c.Network.Federation} {
		for _, name := range names {
			if _, ok := flows[name]; !ok {
				return fmt.Errorf("unknown network flow %q", name)
			}
		}
	}
	return nil
}

func generate(c Contract) string {
	var b strings.Builder
	p := func(s string) { b.WriteString(s); b.WriteByte('\n') }

	p("#!/usr/sbin/nft -f")
	p("# Generated by nixos-shield from contract: " + c.Service)
	p("# Default-deny. Only what the contract declares is allowed.")
	p("")
	p("table inet nixos_shield {")

	p("  chain input {")
	p("    type filter hook input priority 0; policy drop;")
	p("    ct state established,related accept")
	p(`    iif "lo" accept`)
	p("    ip protocol icmp accept")
	p("    ip6 nexthdr icmpv6 accept")
	for _, port := range sortedInts(c.Network.Inbound) {
		p(fmt.Sprintf("    tcp dport %d accept   # inbound (contract)", port))
	}
	p("  }")

	p("  chain output {")
	p("    type filter hook output priority 0; policy drop;")
	p("    ct state established,related accept")
	p(`    oif "lo" accept`)
	seen := map[string]bool{}
	emit := func(flow string) {
		for _, r := range flows[flow] {
			key := fmt.Sprintf("%s%d", r.proto, r.port)
			if seen[key] {
				continue
			}
			seen[key] = true
			p(fmt.Sprintf("    %s dport %d accept   # %s", r.proto, r.port, r.note))
		}
	}
	for _, f := range c.Network.Outbound {
		emit(f)
	}
	for _, f := range c.Network.Federation {
		emit(f)
	}
	p("  }")
	p("}")
	return b.String()
}

func sortedInts(in []int) []int {
	out := append([]int{}, in...)
	sort.Ints(out)
	return out
}
